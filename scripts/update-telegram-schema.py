"""Generate pinned Telegram method/type metadata from the official Bot API HTML."""

import html
import json
import re
import sys
from datetime import date
from pathlib import Path
from urllib.request import urlopen

URL = "https://core.telegram.org/bots/api"


def plain(value):
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", value)).split())


def generate(document):
    headings = list(re.finditer(r"<h4[^>]*>(.*?)</h4>", document, re.S))
    sections = {}
    for index, heading in enumerate(headings):
        name = plain(heading.group(1))
        if re.fullmatch(r"[A-Za-z][A-Za-z0-9]+", name):
            end = (
                headings[index + 1].start()
                if index + 1 < len(headings)
                else len(document)
            )
            sections[name] = document[heading.end() : end]

    definitions = {}
    for name, body in sections.items():
        table = re.search(r"<table[^>]*>(.*?)</table>", body, re.S)
        fields = {}
        if table:
            for row in re.findall(r"<tr[^>]*>(.*?)</tr>", table.group(1), re.S):
                cells = [
                    plain(cell)
                    for cell in re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)
                ]
                if len(cells) not in (3, 4):
                    continue
                field, kind = cells[:2]
                description = cells[-1]
                required = (
                    cells[2] == "Yes"
                    if len(cells) == 4
                    else not description.startswith("Optional")
                )
                info = {"type": kind, "required": required, "description": description}
                literal = re.search(r'(?:must be|always) ["“]([^"”]+)["”]', description)
                if literal and kind == "String":
                    info["literal"] = literal.group(1)
                elif field == "type" and kind == "String":
                    discriminator = re.search(
                        r"must be ([a-z][a-z0-9_]*)\b", description
                    )
                    if discriminator and discriminator.group(1) not in {
                        "one",
                        "a",
                        "an",
                        "either",
                        "the",
                    }:
                        info["literal"] = discriminator.group(1)
                fields[field] = info
        if fields or name[0].islower():
            definitions[name] = {"fields": fields}
        else:
            listing = re.search(r"<ul[^>]*>(.*?)</ul>", body, re.S)
            if listing:
                variants = [
                    plain(label)
                    for label in re.findall(
                        r'<a href="#[^"]+">(.*?)</a>', listing.group(1), re.S
                    )
                ]
                variants = [variant for variant in variants if variant in sections]
                if variants:
                    definitions[name] = {"variants": variants}

    methods = {name: info for name, info in definitions.items() if name[0].islower()}
    assert len(methods) > 150, "Official documentation parser found too few methods"
    assert "correct_option_ids" in methods["sendPoll"]["fields"]
    assert "text" in definitions["InputPollOption"]["fields"]
    needed = set()

    def include(kind):
        for token in re.findall(r"[A-Z][A-Za-z0-9]+", kind):
            if token not in definitions or token in needed or token in methods:
                continue
            needed.add(token)
            for field in definitions[token].get("fields", {}).values():
                include(field["type"])
            for variant in definitions[token].get("variants", []):
                include(variant)

    for method in methods.values():
        for field in method["fields"].values():
            include(field["type"])
    return {
        "source": URL,
        "retrieved": str(date.today()),
        "methods": methods,
        "types": {name: definitions[name] for name in sorted(needed)},
    }


if __name__ == "__main__":
    document = (
        Path(sys.argv[1]).read_text()
        if len(sys.argv) > 1
        else urlopen(URL, timeout=30).read().decode()
    )
    data = generate(document)
    target = Path(__file__).resolve().parents[1] / "agent/lib/bot-schema.ts"
    target.write_text(
        "// Generated by scripts/update-telegram-schema.py from official Telegram documentation.\nexport default "
        + json.dumps(data, indent=2, ensure_ascii=False)
        + ";\n"
    )
    print(
        f"Generated {len(data['methods'])} methods and {len(data['types'])} nested types"
    )
